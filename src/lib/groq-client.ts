export function getModelStatus() {
  const now = Date.now();
  return GROQ_MODELS.map((m) => ({
    id: m.id,
    label: m.label,
    available: (rateLimitedUntil[m.id] ?? 0) < now,
    rateLimitedUntil: rateLimitedUntil[m.id]
      ? new Date(rateLimitedUntil[m.id]).toLocaleTimeString('ru-RU')
      : null,
  }));
}
